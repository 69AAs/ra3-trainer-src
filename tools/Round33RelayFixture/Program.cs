using Ra3Trainer.Core.Runtime;
using System.Text.Json;
var root=Path.GetFullPath(args.FirstOrDefault()??".");
var entries=File.ReadLines(Path.Combine(root,"artifacts/round33/entry-format-tests.log")).Where(l=>l.StartsWith("osd-entry ")).ToArray();
if(entries.Length!=2)throw new Exception("Native fixture output missing");
var directory=Path.Combine(root,"artifacts/round33/relay-fixture",Guid.NewGuid().ToString("N"));
using var log=TrainerSessionLog.Open(directory);
log.Write("fixture",new{qualification="Offline native formatter output; not host Reset evidence"});
var relay=new OverlayEntryRelay();
var input="osd-session 0000000000000001\n"+string.Join('\n',entries)+"\n";
relay.Forward(input,1,(kind,message)=>log.Write(kind,new{message}));
relay.Forward(input,1,(kind,message)=>log.Write(kind,new{message}));
using var file=new FileStream(log.FilePath,FileMode.Open,FileAccess.Read,FileShare.ReadWrite);
using var reader=new StreamReader(file); var text=reader.ReadToEnd();
var actual=text.Split('\n',StringSplitOptions.RemoveEmptyEntries).Select(l=>JsonDocument.Parse(l)).Where(j=>j.RootElement.GetProperty("event").GetString()=="osd-entry").Select(j=>j.RootElement.GetProperty("data").GetProperty("message").GetString()).ToArray();
if(!actual.SequenceEqual(entries))throw new Exception("Session relay changed native fields or duplicated lines");
Directory.CreateDirectory(Path.Combine(root,"docs/round33-evidence"));
File.WriteAllText(Path.Combine(root,"docs/round33-evidence/C-session-fixture.jsonl"),text);
Console.WriteLine("PASS native formatter -> OverlayEntryRelay -> TrainerSessionLog: 2 records identical; duplicate poll adds 0. FIXTURE ONLY.");
