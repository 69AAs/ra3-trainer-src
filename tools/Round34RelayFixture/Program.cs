using Ra3Trainer.Core.Runtime;
using System.Text.Json;
var root=Path.GetFullPath(args.FirstOrDefault()??".");
var entries=File.ReadLines(Path.Combine(root,"artifacts/round34/texture-fixture.log")).Where(l=>l.StartsWith("osd-draw-")).Distinct().ToArray();
if(entries.Length<50 || !entries.Any(l=>l.Contains("name=ApplyStateBlock hr=00000000"))) throw new Exception("Native fixture incomplete");
var directory=Path.Combine(root,"artifacts/round34/relay-fixture",Guid.NewGuid().ToString("N"));
using var log=TrainerSessionLog.Open(directory);
log.Write("fixture",new{qualification="Synthetic COM MSAA; actual GDI; NOT game/GPU evidence"});
var relay=new OverlayEntryRelay();
var input="osd-session 0000000000000001\n"+string.Join('\n',entries)+"\n";
relay.Forward(input,1,(kind,message)=>log.Write(kind,new{message}));
relay.Forward(input,1,(kind,message)=>log.Write(kind,new{message}));
using var file=new FileStream(log.FilePath,FileMode.Open,FileAccess.Read,FileShare.ReadWrite);
using var reader=new StreamReader(file);var text=reader.ReadToEnd();
var actual=text.Split('\n',StringSplitOptions.RemoveEmptyEntries).Select(l=>JsonDocument.Parse(l)).Where(j=>j.RootElement.GetProperty("event").GetString()!.StartsWith("osd-draw-")).Select(j=>j.RootElement.GetProperty("data").GetProperty("message").GetString()).ToArray();
if(!actual.SequenceEqual(entries))throw new Exception("Draw relay changed fields or duplicated records");
Directory.CreateDirectory(Path.Combine(root,"docs/round34-evidence"));
File.WriteAllText(Path.Combine(root,"docs/round34-evidence/session-fixture.jsonl"),text);
Console.WriteLine($"PASS native renderer -> OverlayEntryRelay -> TrainerSessionLog: {entries.Length} records verbatim; duplicate poll adds 0. FIXTURE ONLY.");
